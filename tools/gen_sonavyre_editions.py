#!/usr/bin/env python3
"""Generate distributable subsets without changing original program words or labels."""
import re, json, sys
from pathlib import Path
root=Path(__file__).resolve().parent.parent
base=root/'src/sonavyre/presets'
def read(file,prefix):
 s=(base/file).read_text()
 def part(suffix):
  return s.split('static const '+('uint32_t' if suffix=='BANK' else 'char*')+' '+prefix+suffix,1)[1].split('= {',1)[1].split('};',1)[0]
 rows=re.findall(r'\{([^{}]+)\}',part('BANK'))
 names=re.findall(r'"([^"\n]*)"',part('NAMES'))
 labels=re.findall(r'\{([^{}]+)\}',part('LABELS'))
 return list(zip(rows,names,labels))
allrows=read('OriginalBank.hpp','FXAID_DEFAULT_')[:8]+read('CompleteBank.hpp','FXAIDPRO_DEFAULT_')
free=list(range(8))+[132,160,149,135]
studio=free+[33,34,35,36,37,38,39,41,44,46,47,49,52,53,55,59,60,62,70,71,75,83,84,85,86,91,92,93,95,99,102,105,107,108,110,111,119,123,125,127,130,133,138,141,150,151,162,163,166,174,181,204]
assert len(free)==12 and len(studio)==64 and len(set(studio))==64
for name,ids in [('Free',free),('Studio',studio)]:
 rows=[allrows[i] for i in ids]
 text='#pragma once\n#include <cstdint>\n// Generated by tools/gen_sonavyre_editions.py. See AUDIT.md for source attribution.\n'
 text+=f'static const int SONAVYRE_FACTORY_IDS[{len(ids)}] = {{'+','.join(map(str,ids))+'};\n'
 text+=f'static const uint32_t SONAVYRE_EDITION_BANK[{len(ids)}][128] = {{\n'+',\n'.join('{'+r[0]+'}' for r in rows)+'\n};\n'
 text+=f'static const char* SONAVYRE_EDITION_NAMES[{len(ids)}] = {{'+','.join(json.dumps(r[1]) for r in rows)+'};\n'
 text+=f'static const char* SONAVYRE_EDITION_LABELS[{len(ids)}][3] = {{'+','.join('{'+r[2]+'}' for r in rows)+'};\n'
 target=base/(name+'Bank.hpp')
 if '--check' in sys.argv:
  if target.read_text()!=text:raise SystemExit(f'Stale edition bank: {target}')
 else:target.write_text(text)
 print(name+': '+', '.join(r[1] for r in rows))
