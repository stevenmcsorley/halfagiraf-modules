#!/usr/bin/env python3
"""Preserve the 38 catalogue binaries absent from the original 200-slot bank.

Source data is from the untouched upstream offline editor. The firmware image
container is deliberately not included. Project owner authorized use on 2026-10-23.
"""
from pathlib import Path
import base64,json,re,sys
family=Path(__file__).resolve().parent.parent
candidates=list((family.parent/'upstream-halfagiraf-vcv/tools').glob('*/data.json'))
assert len(candidates)==1, 'Specify an unambiguous offline editor data source'
source=candidates[0]
header=(family/'src/sonavyre/presets/CompleteBank.hpp').read_text()
part=header.split('static const uint32_t SONAVYRE_COMPLETE_BANK[200][128] = {')[1].split('};')[0]
pro={b''.join(int(w,16).to_bytes(4,'big')for w in re.findall(r'0x[0-9a-fA-F]+',row))for row in re.findall(r'\{([^{}]+)\}',part)}
programs=[]
for p in json.loads(source.read_text())['programs']:
 b=base64.b64decode(p['bin']);assert len(b)==512
 assert all((b[k]&31)<=20 for k in range(3,512,4))
 if b not in pro:programs.append((p,b))
assert len(programs)==38
s='#pragma once\n#include <cstdint>\n// Original third-party program bytes and metadata from the upstream offline editor.\n// Included on the project owner\'s explicit confirmation of rights; see AUDIT.md.\n// Generated by tools/gen_sonavyre_catalogue.py. No firmware container is included.\n\n'
s+='static const uint32_t SONAVYRE_EXTRA_BANK[38][128] = {\n'
for p,b in programs:s+=' {'+', '.join(f'0x{int.from_bytes(b[i:i+4],"big"):08x}'for i in range(0,512,4))+'},\n'
s+='};\nstatic const char* SONAVYRE_EXTRA_NAMES[38] = {\n'+''.join(' '+json.dumps(p['name'])+',\n'for p,b in programs)+'};\n'
s+='static const char* SONAVYRE_EXTRA_LABELS[38][3] = {\n'+''.join(' {'+', '.join(json.dumps(p[k])for k in ['p1','p2','p3'])+'},\n'for p,b in programs)+'};\n'
target=family/'src/sonavyre/presets/CatalogueExtras.hpp'
if '--check' in sys.argv:
 assert target.read_text()==s, 'Catalogue bytes or metadata diverged from upstream source data'
else:target.write_text(s)
print('Preserved 38 additional programs byte-for-byte; full catalogue has 238 unique binaries.')
